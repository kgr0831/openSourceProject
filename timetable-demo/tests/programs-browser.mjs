import test from 'node:test';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {createTimetableServer} from '../server.mjs';
import {scheduler} from './fixtures/schedule.mjs';
import {programSnapshot,programBridge,programNow} from './fixtures/programs.mjs';
import {programStorageKey} from '../public/program-model.mjs';
import {createPlannerStore,storageKey} from '../public/planner.js';
const {chromium}=createRequire(new URL('../../lms-parser/package.json',import.meta.url))('playwright');
test('진로 > 비교과 추천: 저장·복원·실패 보존·학교 링크·기간 갱신·모바일·일정 보존',{timeout:45000},async t=>{
  let snapshot=programSnapshot();const bridge=programBridge();
  const server=createTimetableServer({scheduler,port:0,bridge,programSource:{load:async()=>structuredClone(snapshot)},programNow:()=>programNow,
    createLms:async()=>({resume(){},view:()=>({connection:'disconnected'}),async close(){}})});
  await new Promise(r=>server.listen(0,'127.0.0.1',r));t.after(async()=>{await server.closeServices();await new Promise(r=>server.close(r))});
  const browser=await chromium.launch({channel:'chrome',headless:true});t.after(()=>browser.close());
  const page=await browser.newPage({viewport:{width:1440,height:1050},reducedMotion:'reduce',timezoneId:'America/Los_Angeles'});
  page.setDefaultTimeout(7000);await page.clock.install({time:programNow});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const mem=new Map(),planner=createPlannerStore({getItem:k=>mem.get(k)??null,setItem:(k,v)=>mem.set(k,v)});
  planner.setSemester({sections:[{id:'ml-01',courseId:'ml',name:'머신러닝',credits:3,building:'정보과학관',meetings:[[0,600,660]]}]},'2026-11-23','2026-12-06');
  const original=JSON.stringify(planner.data);
  await page.addInitScript(({key,value})=>{if(!localStorage.getItem(key))localStorage.setItem(key,value)},{key:storageKey,value:original});
  const base=`http://127.0.0.1:${server.address().port}`;
  await page.goto(base+'/#start');await page.locator('main a[href="#programs"]').first().click();
  await page.locator('#program-goal').fill('컴퓨터비전');await page.locator('[data-action="program-evaluate"]:enabled').waitFor();
  await page.locator('[data-action="program-evaluate"]').click();await page.locator('.program-card').first().waitFor();
  assert.equal(await page.locator('.program-card').count(),2);
  assert.match(await page.locator('.program-results').innerText(),/제목 기반/);
  assert.equal(await page.locator('.program-card a[href^="https://path.ssu.ac.kr/"]').count(),4);
  assert.equal(await page.evaluate(key=>localStorage.getItem(key),storageKey),original);
  const saved=await page.evaluate(key=>localStorage.getItem(key),programStorageKey);assert.ok(saved);
  await page.locator('#program-upcoming').check();await page.locator('[data-action="program-evaluate"]').click();
  await page.waitForFunction(()=>document.querySelectorAll('.program-card').length===3);
  assert.match(await page.locator('.program-results').innerText(),/모집 예정/);
  await page.locator('.program-card details').first().locator('summary').click();
  await page.screenshot({path:'/private/tmp/ssu-programs-desktop.png',fullPage:false});
  await page.reload();await page.locator('.program-card').first().waitFor();assert.equal(await page.locator('.program-card').count(),3);
  const preserved=await page.evaluate(key=>localStorage.getItem(key),programStorageKey);
  await page.locator('#program-goal').fill('실패 확인');await page.locator('[data-action="program-evaluate"]').click();
  await page.getByText('비교과 검색 실패 테스트',{exact:true}).waitFor();
  assert.equal(await page.evaluate(key=>localStorage.getItem(key),programStorageKey),preserved);
  assert.equal(await page.evaluate(key=>localStorage.getItem(key),storageKey),original);
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:'/private/tmp/ssu-programs-mobile.png',fullPage:false});
  snapshot.programs[0].sourceStatus='신청마감';
  await page.locator('[data-action="program-refresh"]').click();
  await page.getByText('저장된 추천의 모집 정보가 변경되었어요. 다시 검색해 주세요.',{exact:true}).waitFor();
  assert.equal(await page.locator('.program-card').count(),0);
  await page.locator('#program-goal').fill('AI');await page.locator('[data-action="program-evaluate"]').click();
  await page.locator('.program-card').first().waitFor();assert.equal(await page.locator('.program-card').count(),2);
  snapshot.collectedAt='2026-11-01T00:00:00Z';await page.locator('[data-action="program-refresh"]').click();
  await page.getByText(/비교과 모집 정보가 오래되어/).waitFor();
  assert.equal(await page.locator('[data-action="program-evaluate"]').isDisabled(),true);
  assert.equal(await page.locator('.program-card').count(),0);
  assert.deepEqual(errors,[]);
});
